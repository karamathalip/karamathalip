// ─── KiscoLearning (root composition) ────────────────────────────────────────

export const KiscoLearning: React.FC = () => {
  return (
    <AbsoluteFill>
      {/* Original narration audio plays under the whole video */}
      <Audio
        src={staticFile("audio/kisco/narration.mp3")}
        volume={1}
        startFrom={0}
      />

      {/* Scene sequences timed to narration */}
      {SCENES.map((scene) => {
        const startFrame = Math.round(scene.startSec * FPS);
        const endFrame   = Math.round(scene.endSec   * FPS);
        const dur        = endFrame - startFrame;

        return (
          <Sequence
            key={scene.id}
            from={startFrame}
            durationInFrames={dur}
            name={scene.id}
          >
            <KiscoScene scene={scene} />
          </Sequence>
        );
      })}
    </AbsoluteFill>
  );
};
