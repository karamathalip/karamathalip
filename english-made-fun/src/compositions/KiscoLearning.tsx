// ─── KenBurns helper ──────────────────────────────────────────────────────────

function useKenBurns(durationInFrames: number, dir: "in" | "out") {
  const frame = useCurrentFrame();
  const progress = frame / Math.max(durationInFrames - 1, 1);
  // Subtle zoom: 1.0 ↔ 1.12 over the scene duration
  const scale = dir === "in"
    ? interpolate(progress, [0, 1], [1.0, 1.12])
    : interpolate(progress, [0, 1], [1.12, 1.0]);
  return { transform: `scale(${scale})`, transformOrigin: "center center" };
}

// ─── Title spring animation ───────────────────────────────────────────────────

function useTitleAnimation() {
  const frame = useCurrentFrame();
  const { fps } = useVideoConfig();
  const scale = spring({ fps, frame, config: { damping: 12, stiffness: 120 }, from: 0.7, to: 1 });
  const opacity = interpolate(frame, [0, 12], [0, 1], { extrapolateRight: "clamp" });
  return { transform: `scale(${scale})`, opacity };
}

// ─── SubTitle fade ────────────────────────────────────────────────────────────

function useSubtitleAnimation() {
  const frame = useCurrentFrame();
  const opacity = interpolate(frame, [10, 25], [0, 1], { extrapolateRight: "clamp" });
  const translateY = interpolate(frame, [10, 25], [20, 0], { extrapolateRight: "clamp" });
  return { opacity, transform: `translateY(${translateY}px)` };
}

// ─── KiscoScene ───────────────────────────────────────────────────────────────

